// Generated report output has one source of truth: the recorded raw JSON run.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const directory = fileURLToPath(new URL('.', import.meta.url));
const source = resolve(process.argv[2] || resolve(directory, 'results/latest.json'));
const output = resolve(directory, 'RESULTS.md');
const data = JSON.parse(await readFile(source, 'utf8'));
const labels = {
  open_gift_book: 'Open gift book',
  first_open_penguins: 'First open: Penguins',
  first_open_titanic: 'First open: Titanic',
  warm_switch_penguins: 'Warm switch: Penguins',
  warm_switch_titanic: 'Warm switch: Titanic',
  plain_edit_penguins: 'Plain edit: Penguins',
  sum_edit_penguins: 'Edit + SUM: Penguins',
  plain_edit_titanic: 'Plain edit: Titanic',
  sum_edit_titanic: 'Edit + SUM: Titanic',
};
const rows = Object.keys(data.apps.ts.summary).map(metric => {
  const ts = data.apps.ts.summary[metric];
  const rust = data.apps.rust.summary[metric];
  return `| ${labels[metric]} | ${ts.n} | ${ts.medianMs.toFixed(2)} | ${rust.medianMs.toFixed(2)} | ${ts.p95Ms.toFixed(2)} | ${rust.p95Ms.toFixed(2)} |`;
});
const totals = Object.entries(data.apps).map(([name, app]) => {
  const bytes = app.assets.reduce((sum, file) => sum + file.bytes, 0);
  const gzip = app.assets.reduce((sum, file) => sum + file.gzipBytes, 0);
  return `| ${name === 'ts' ? 'TypeScript / React' : 'Rust / WASM / Yew'} | ${(bytes / 1024).toFixed(1)} | ${(gzip / 1024).toFixed(1)} |`;
});
const report = `# Spreadsheet application results

<!-- Generated by summarize.mjs from ${relative(directory, source)}. Do not edit independently. -->

Recorded ${data.generatedAt}. [Method and reproduction](README.md) · [Raw samples](${relative(dirname(output), source)}).

Host: ${data.environment.cpu}, ${data.environment.arch}, ${data.environment.platform} ${data.environment.release}, ${data.environment.logicalCpus} logical CPUs.
Chromium ${data.environment.chromium}; Node ${data.environment.node}; viewport ${data.environment.viewport.width} × ${data.environment.viewport.height}.

- TS source: [${data.versions.ts.commit.slice(0, 7)}](https://github.com/ggkguelensan/jotai-holo/commit/${data.versions.ts.commit}); dirty at run start: ${data.versions.ts.dirty}.
- Rust source: [${data.versions.rust.commit.slice(0, 7)}](https://github.com/ggkguelensan/jotai-rust/commit/${data.versions.rust.commit}); dirty at run start: ${data.versions.rust.dirty}.
- Builds: ${data.method.builds}.
- Warm order: ${data.method.warmOrder}.

## Browser-local event → DOM timings

All times are milliseconds; lower is better. Each implementation has the same sample count per row. Medians and p95 describe this single machine/run.

| Scenario | n each | TS median | Rust median | TS p95 | Rust p95 |
| --- | ---: | ---: | ---: | ---: | ---: |
${rows.join('\n')}

## Standalone output size

| App | Uncompressed KiB | Sum of gzip KiB |
| --- | ---: | ---: |
${totals.join('\n')}

Gzip is computed offline per file. Servers use uncompressed responses and identical cache policy. The raw artifact lists every build file and hash.

## Interpretation limits

These are **application measurements**, not a language-only or atom-core benchmark.
TS uses lazy sheet restoration, IndexedDB and registry ownership; Rust eagerly
constructs its sheets and uses whole-book localStorage snapshots. First-open
costs therefore occur at different points. Compare startup together with first
sample opens, not an isolated switch number. Warm switches still exercise different
component, registry and persistence paths.

Editing includes the app's parsing, topology checks, demanded calculations and
DOM work up to the measured result. The SUM fixtures contain 344 and 891 source
cells. It does not measure a standalone formula engine or time to paint. No heap
comparison is made because JS heap metrics omit WASM linear memory.

The runner verified identical input bytes and expected result values for both
apps. See the raw distributions before interpreting small differences; no broad
Rust-versus-TypeScript conclusion follows from these two implementations.
`;
await writeFile(output, report);
console.log(output);
